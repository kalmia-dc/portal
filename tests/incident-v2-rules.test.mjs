import fs from 'node:fs';
import {createRequire} from 'node:module';
import test from 'node:test';
import assert from 'node:assert/strict';
import {createIncidentStore,BASE,decodeRecord} from '../incident-report-store.mjs';
import {newReport} from '../incident-report-core.mjs';
const require=createRequire(new URL('../../package.json',import.meta.url));
const {initializeTestEnvironment,assertFails,assertSucceeds}=require('@firebase/rules-unit-testing');
const api=require('firebase/database');
test('private drafts, immutable history, atomic publication, proxy and withdrawal',async()=>{
 const env=await initializeTestEnvironment({projectId:'demo-incident-v2',database:{host:'127.0.0.1',port:9027,rules:fs.readFileSync('database.rules.json','utf8')}});
 try{
  const users={owner:{active:true,role:'staff',staffId:'author'},other:{active:true,role:'staff',staffId:'other'},admin:{active:true,role:'admin',staffId:'sugihira'},leader:{active:true,role:'staff',staffId:'momo'},terminal:{active:true,role:'terminal',staffId:'terminal'},revoked:{active:false,role:'admin',staffId:'sugihira'}};
  await env.withSecurityRulesDisabled(c=>api.set(api.ref(c.database()),{portalAccess:{users}}));
  const db=id=>env.authenticatedContext(id).database();
  const store=id=>createIncidentStore({db:db(id),api,user:{staffId:users[id].staffId},manager:['admin','leader'].includes(id)});
  const director=await assertSucceeds(store('admin').commit({...newReport('director-auto-confirm'),reporterId:'sugihira',reporterName:'院長',title:'準備中の確認漏れに気づいた',details:'架空の自動確認試験',impact:'0'},{action:'import'}));
  assert.equal(director.review,'confirmed');
  const titlePath='meetingManagement/incidentTitles/v2/director-auto-confirm';
  await assertSucceeds(api.get(api.ref(db('owner'),titlePath)));
  await assertFails(api.set(api.ref(db('other'),titlePath),{text:'不正変更',actor:'other',updatedAt:api.serverTimestamp()}));
  await assertSucceeds(store('admin').saveTitle('v2','director-auto-confirm','準備の確認漏れを処置前に発見した'));
  await assertFails(store('admin').saveTitle('v2','no-source-report','存在しない報告'));
  const persisted=await store('admin').record('director-auto-confirm');
  await assertSucceeds(store('admin').commit(decodeRecord(persisted),{previous:persisted,action:'withdraw',reason:'架空試験'}));
  const hidden=await store('admin').record('director-auto-confirm');
  await assertFails(api.get(api.ref(db('owner'),titlePath)));
  await assertSucceeds(store('admin').commit(decodeRecord(hidden),{previous:hidden,action:'restore',reason:'架空試験の復元'}));

  const unknownDirector=await assertSucceeds(store('admin').commit({...newReport('director-unknown-impact'),reporterId:'sugihira',reporterName:'院長',details:'架空の未確認試験',impact:'unknown'},{action:'import'}));
  assert.equal(unknownDirector.review,'pending');
  const r={...newReport('test-report-001'),reporterId:'author',reporterName:'架空担当',details:'架空の試験',impact:'0'};
  await assertSucceeds(store('owner').saveDraft(r));
  for(const id of ['other','admin','leader','terminal','revoked'])await assertFails(api.get(api.ref(db(id),`${BASE}/drafts/author`)));
  await assertSucceeds(store('admin').saveDraft({...r,reportId:'proxy-report-001'}));
  await assertFails(store('admin').saveDraft({...r,reportId:'proxy-report-001'},1));
  await assertSucceeds(store('owner').commit(r,{action:'submit'}));
  for(const id of ['owner','other','admin','leader','terminal'])await assertSucceeds(api.get(api.ref(db(id),`${BASE}/feed`)));
  for(const id of ['other','terminal','revoked'])await assertFails(store(id).history(r.reportId));
  const previous=await store('owner').record(r.reportId);
  const payload={...decodeRecord(previous),details:'修正した架空の記録'};
  await assertFails(store('other').commit(payload,{previous}));
  await assertSucceeds(store('owner').commit(payload,{previous}));
  await assertFails(store('owner').commit(payload,{previous})); // stale revision
  await assertFails(api.update(api.ref(db('owner'),`${BASE}/feed/${r.reportId}`),{payload:'tampered'}));
  await assertFails(api.set(api.ref(db('owner'),`${BASE}/history/${r.reportId}/r1`),null));
  const latest=await store('admin').record(r.reportId);
  await assertSucceeds(store('admin').commit(decodeRecord(latest),{previous:latest,action:'withdraw',reason:'架空テストの取り下げ'}));
  assert.equal((await api.get(api.ref(db('terminal'),`${BASE}/feed/${r.reportId}`))).exists(),false);
  await assertSucceeds(store('owner').record(r.reportId));
  await assertFails(store('other').record(r.reportId));
  const withdrawn=await store('admin').record(r.reportId);
  await assertSucceeds(store('admin').commit(decodeRecord(withdrawn),{previous:withdrawn,action:'restore',reason:'架空テストの復元'}));
  const restored=await store('admin').record(r.reportId);
  assert.equal(restored.submittedAt,previous.submittedAt);
  await assertSucceeds(store('admin').commit({...decodeRecord(restored),reporterId:'other',reporterName:'訂正先の架空担当'},{previous:restored,reason:'報告者選択の訂正'}));
  await assertFails(store('owner').history(r.reportId));
  await assertSucceeds(store('other').history(r.reportId));
  assert.equal((await api.get(api.ref(db('terminal'),`${BASE}/feed/${r.reportId}/reason`))).exists(),false);
  for(const context of [db('revoked'),env.unauthenticatedContext().database()]){
   await assertFails(api.get(api.ref(context,`${BASE}/feed`)));
   await assertFails(api.set(api.ref(context,`${BASE}/drafts/author/blocked-report`),{owner:'author'}));
  }
  const current=await store('admin').record(r.reportId);
  await assertSucceeds(store('admin').commit(decodeRecord(current),{previous:current,confirmed:true,action:'review'}));
  const checked=await store('admin').record(r.reportId);
  await assertSucceeds(store('leader').commit(decodeRecord(checked),{previous:checked,action:'followup',counterStatus:'in_progress',countermeasure:'架空の対策'}));
  const followup=await store('admin').record(r.reportId);
  assert.equal(followup.review,'confirmed');assert.equal(followup.reviewedAt,checked.reviewedAt);
  await assertFails(store('leader').commit(decodeRecord(followup),{previous:followup,counterStatus:'confirmed'}));
  await assertSucceeds(store('other').commit({...decodeRecord(followup),details:'影響について追記'},{previous:followup}));
  assert.equal((await store('admin').record(r.reportId)).review,'pending');
  const old={id:'old-001',reporterId:'author',reporterName:'旧記録の本人',createdById:'author',createdAt:1700000000000,details:'旧本文',type:'near_miss',level:'A',counterStatus:'confirmed',countermeasure:'保存済み対策',linkedTaskId:'task-old'};
  await env.withSecurityRulesDisabled(c=>api.set(api.ref(c.database(),'meetingManagement/incidentReports/'+old.id),old));
  await assertSucceeds(store('owner').commit({...r,reportId:'legacy_'+old.id},{legacy:old,action:'migrate'}));
  const migrated=await store('owner').record('legacy_'+old.id);
  assert.equal(migrated.counterStatus,'confirmed');assert.equal(migrated.submittedAt,old.createdAt);assert.deepEqual(JSON.parse(migrated.legacy),old);
  assert.equal((await api.get(api.ref(db('owner'),'meetingManagement/incidentReports/'+old.id))).exists(),false);
  await assertFails(store('owner').commit({...r,reportId:'legacy_fake-001'},{legacy:{...old,id:'fake-001'}}));
  await assertFails(store('owner').commit(decodeRecord(migrated),{previous:migrated,linkedOriginals:'changed'}));
  await env.withSecurityRulesDisabled(c=>api.set(api.ref(c.database(),'meetingManagement/tasks/task-old'),{detail:'旧本文と対策の混在（架空）',sourceIncidentId:old.id}));
  await assertFails(store('admin').commit(decodeRecord(migrated),{previous:migrated,action:'withdraw',reason:'共有文の確認前'}));
  await assertSucceeds(store('admin').commit(decodeRecord(migrated),{previous:migrated,action:'withdraw',reason:'架空の取り下げ',linkedOriginals:'旧本文と対策の混在（架空）',extraUpdates:{'meetingManagement/tasks/task-old/detail':'確認済みの対策のみ','meetingManagement/tasks/task-old/sourceIncidentWithdrawn':true}}));
  const sharedTask=(await api.get(api.ref(db('other'),'meetingManagement/tasks/task-old'))).val();
  assert.equal(sharedTask.detail,'確認済みの対策のみ');assert.equal(sharedTask.sourceIncidentWithdrawn,true);
  await assertFails(api.get(api.ref(db('other'),`${BASE}/records/legacy_${old.id}/linkedOriginals`)));
  const imported={...r,reportId:'import-proxy-001'};
  await assertSucceeds(store('admin').saveDraft(imported,0,true));
  await assertSucceeds(store('owner').commit(imported,{action:'submit'}));
  const importedRecord=await store('owner').record(imported.reportId);
  assert.equal(importedRecord.owner,'author');assert.equal(importedRecord.importedBy,'sugihira');assert.equal(importedRecord.actor,'author');
  await assertFails(store('terminal').commit({...r,reportId:'terminal-report-001',reporterId:'terminal'}));
  await env.withSecurityRulesDisabled(c=>api.set(api.ref(c.database(),'staffLifecycle/author'),{state:'stopped'}));
  await assertFails(store('owner').record(imported.reportId));
  await assertFails(store('owner').saveDraft({...r,reportId:'stopped-report-001'}));
 }finally{await env.cleanup();}
});
